// Картинка товара, пока у него нет фото: пиктограмма самого товара на мягком фоне цвета группы.
// Порядок: подкатегория одного фрукта/овоща («Яблоки» → сорт «Апорт» тоже яблоко), название товара,
// подкатегория. Нет подходящей — null: тогда рисуем инициалы, а не случайную картинку.
// Совпадение — по русским названиям каталога. В JS \b не работает с кириллицей, поэтому границы — (^|\s).

// Подкатегории, в которых все товары — один вид (часто названы только сортом: «Апорт», «Чили», «Хас Перу»).
const SINGLE_CATEGORY: Record<string, string | null> = {
  яблоки: '🍎', груши: '🍐', виноград: '🍇', бананы: '🍌', авокадо: '🥑', ананасы: '🍍', манго: '🥭', киви: '🥝',
  томаты: '🍅', огурцы: '🥒', перцы: '🫑', грибы: '🍄', бахчевые: null, хурма: null, гранаты: null,
};

const RULES: [RegExp, string][] = [
  // Корейские салаты и соленья — раньше овощей: «Морковь по-корейски» — салат, а не морковь.
  [/по-корейски|кимчи|фунчоз|чука|папоротник|(^|\s)хе($|\s)/, '🥗'],
  [/квашен|солён|солен|маринован|варень|джем/, '🫙'],
  // Молочка — раньше фруктов: «Сливки» не слива и не томат.
  [/(^|\s)сливки($|\s)|молок|кефир|бифидок|айран|ряженк|катык|простокваш|йогурт|кумыс|шубат|саумал|сметан|творог/, '🥛'],
  [/сыр|сулугуни|моцарелл|брынз|иримшик|курт/, '🧀'], [/масло сливоч/, '🧈'], [/яйц/, '🥚'],
  // Овощи и зелень
  [/картоф|картош/, '🥔'], [/батат/, '🍠'], [/морков/, '🥕'], [/чеснок|черемш/, '🧄'],
  [/зелёный лук|укроп|кинз|петруш|мят|щавел|базилик|тархун|розмарин|тимьян|орегано|мелисс|портулак|жусай|сельдерей \(лист/, '🌿'],
  [/(^|\s)лук|шалот|порей|басай/, '🧅'],
  [/томат|помидор|черри|жёлтые сливки|сливки на веточке|бычье сердце|чёрный принц|равва/, '🍅'], [/огур|корнишон/, '🥒'],
  [/перец/, '🫑'], [/баклажан/, '🍆'], [/кукуруз|(^|\s)корн($|\s)/, '🌽'], [/брокколи/, '🥦'],
  [/капуст|салат|айсберг|романо|мангольд|шпинат|руккол|кресс/, '🥬'], [/горошек|фасол|бамия/, '🫛'],
  [/имбир|куркум|хрен/, '🫚'], [/гриб|шампиньон|вёшенк|вешенк|лисичк|опят|портобелло|эноки|шиитаке/, '🍄'],
  [/тыкв|патиссон/, '🎃'],
  // Фрукты и ягоды
  [/лимон|лайм/, '🍋'], [/мандарин|клементин|минеол|апельсин|грейпфрут|помело|свити|кумкват/, '🍊'], [/банан/, '🍌'],
  [/груш/, '🍐'], [/ананас/, '🍍'], [/манго/, '🥭'], [/киви/, '🥝'], [/кокос/, '🥥'], [/яблок/, '🍎'],
  [/виноград|кишмиш|изюм/, '🍇'], [/персик|нектарин|абрикос|курага|урюк/, '🍑'], [/черешн|вишн/, '🍒'],
  [/клубник/, '🍓'], [/голубик|ежевик|смородин|брусник|клюкв|крыжовн|малин|(^|\s)слива($|\s)|алыч|чернослив/, '🫐'],
  [/арбуз/, '🍉'], [/дын/, '🍈'],
  // Орехи, мёд
  [/орех|миндал|фундук|кешью|фисташ|арахис|макадам|пекан/, '🥜'], [/мёд|прополис/, '🍯'],
  // Мясо и рыба
  [/куриц|курин|индейк|(^|\s)утка|гусь|перепёл/, '🍗'], [/кревет/, '🦐'], [/кальмар/, '🦑'],
  [/судак|сазан|лосос|сельд|скумбри|карп|(^|\s)сом($|\s)|толстолоб|рыб/, '🐟'],
  [/говяд|баран|конин|фарш|рёбр|вырезк|антрекот|грудинк|голяшк|жая|казы|шужык|сур-ет|печень|курдюч|(^|\s)карта($|\s)/, '🥩'],
];

function byRules(text: string): string | null {
  const l = text.toLowerCase();
  return RULES.find(([re]) => re.test(l))?.[1] ?? null;
}

/** Пиктограмма товара или null (нет точной — показываем инициалы, а не похожую картинку). */
export function pictureFor(name: string, category: string): string | null {
  const cat = category.toLowerCase().trim();
  if (cat in SINGLE_CATEGORY) {
    const pic = SINGLE_CATEGORY[cat];
    // «Бахчевые»: арбуз или дыня — по названию; «Хурма», «Гранаты» — эмодзи нет.
    return pic ?? byRules(name);
  }
  return byRules(name) ?? byRules(category);
}

/** Инициалы для товара без пиктограммы: «Королёк» → «Ко». */
export function initialsFor(name: string): string {
  return name.trim().slice(0, 2);
}

/** Мягкий фон плашки по группе каталога. */
export function tintFor(group: string): string {
  const g = group.toLowerCase();
  if (/фрукт/.test(g)) return '#FCEDE6';
  if (/овощ/.test(g)) return '#E9F2EB';
  if (/салат/.test(g)) return '#EEF3E2';
  if (/орех/.test(g)) return '#F4ECDD';
  if (/молоч|яйц/.test(g)) return '#FBF4E2';
  if (/мяс|рыб/.test(g)) return '#F9E6E4';
  if (/мёд/.test(g)) return '#FBF0D9';
  return '#F4F2F0';
}
