// Переводы клиентской части сайта: ru (основной), kk, en.
// Язык хранится в cookie `lang`; без неё — по Accept-Language браузера, иначе русский.

export type Lang = 'ru' | 'kk' | 'en';
export const LANGS: Lang[] = ['ru', 'kk', 'en'];
export const LANG_COOKIE = 'lang';
export const LANG_LABELS: Record<Lang, string> = { ru: 'Рус', kk: 'Қаз', en: 'Eng' };
/** Локаль для дат и чисел. */
export const LOCALES: Record<Lang, string> = { ru: 'ru-RU', kk: 'kk-KZ', en: 'en-GB' };

export function isLang(v: unknown): v is Lang {
  return v === 'ru' || v === 'kk' || v === 'en';
}

/** Выбор языка: сохранённый в cookie, иначе первый подходящий из Accept-Language, иначе ru. */
export function pickLang(cookie: string | undefined, acceptLanguage: string | null): Lang {
  if (isLang(cookie)) return cookie;
  for (const part of (acceptLanguage ?? '').split(',')) {
    const code = part.trim().slice(0, 2).toLowerCase();
    if (isLang(code)) return code;
  }
  return 'ru';
}

/** Текст из i18n-поля каталога { ru, kk, en } на нужном языке (запасной — русский). */
export function localized(v: { ru: string; kk?: string; en?: string }, lang: Lang): string {
  return v[lang] || v.ru;
}

